const probeHtml = `<!doctype html><html><head>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>html,body{margin:0;padding:0;background:#222}#frame{border:0;display:block}</style>
</head><body>
<pre id="result" style="display:none">pending</pre>
<iframe id="frame" src="about:blank"></iframe>
<script>
const W = ${width};
const H = ${height};
const route = new URLSearchParams(location.search).get('r') || '/';
const act = new URLSearchParams(location.search).get('act') || '';
const out = document.getElementById('result');
let clicked = false;
const f = document.getElementById('frame');
// Turn the app's animations off for every run. Headless Chrome does not
// advance requestAnimationFrame reliably under a virtual time budget, so
// enter animations were being photographed half-finished (an empty chart,
// an invisible sheet). Animations off makes the screenshots deterministic and
// matches what a reduced-motion user sees.
try { localStorage.setItem('pixel_animations_enabled', 'false'); } catch {}
f.style.width = W + 'px';
f.style.height = H + 'px';
f.src = ${JSON.stringify(base)} + '/#' + route;
f.onload = () => {
  setTimeout(() => {
    const d = f.contentDocument;
    const doClick = () => {
      // Optional interaction before measuring — used to open the mobile
      // MORE sheet and check that the bottom sheet itself fits.
      if (act === 'click-more') {
        const btn = d && d.querySelector('[aria-haspopup="dialog"]');
        if (btn) btn.click();
      }
    };
    const measure = () => {
    try {
      const over = [];
      // An element inside a deliberately horizontally scrollable strip is not
      // a layout defect — the strip scrolls. Only elements that overflow
      // their *page* count as bugs.
      const inScroller = (el) => {
        let p = el.parentElement;
        while (p && p !== d.body) {
          const ox = getComputedStyle(p).overflowX;
          if (ox === 'auto' || ox === 'scroll') return true;
          p = p.parentElement;
        }
        return false;
      };
      d.querySelectorAll('body *').forEach(el => {
        const r = el.getBoundingClientRect();
        if (r.width === 0 || r.height === 0) return;
        if (r.right > W + 1 && !inScroller(el)) {
          over.push({
            tag: el.tagName.toLowerCase(),
            cls: (el.className || '').toString().slice(0, 100),
            right: Math.round(r.right),
            w: Math.round(r.width),
          });
        }
      });
      const roots = over.filter(o => !over.some(p =>
        p !== o && p.right >= o.right && p.w >= o.w && p.cls !== o.cls));
      const main = d.querySelector('main');
      const page = main && main.firstElementChild;
      const dlg = d.querySelector('[role="dialog"]');
      const dlgRect = dlg && dlg.getBoundingClientRect();

      // Type-scale check: every piece of visible text must sit on the
      // ladder in src/index.css. Anything below 7px is noise in a pixel
      // font and used to be the single most common size in the app.
      const MIN_PX = 7;
      const fontSizes = {};
      const fontFamilies = {};
      const tooSmall = [];
      d.querySelectorAll('body *').forEach(el => {
        const txt = Array.from(el.childNodes)
          .filter(n => n.nodeType === 3)
          .map(n => n.textContent.trim())
          .join(' ')
          .trim();
        if (!txt) return;
        const r = el.getBoundingClientRect();
        if (r.width === 0 || r.height === 0) return;
        const cs = getComputedStyle(el);
        const fs = Math.round(parseFloat(cs.fontSize) * 10) / 10;
        fontSizes[fs] = (fontSizes[fs] || 0) + 1;
        const fam = cs.fontFamily.split(',')[0].replace(/["']/g, '');
        fontFamilies[fam] = (fontFamilies[fam] || 0) + 1;
        if (fs < MIN_PX) {
          tooSmall.push({ fs, txt: txt.slice(0, 40), tag: el.tagName.toLowerCase() });
        }
      });

      out.textContent = 'PROBE:' + JSON.stringify({
        clicked: clicked,
        docScrollW: d.documentElement.scrollWidth,
        viewport: W,
        count: over.length,
        dialogs: d.querySelectorAll('[role="dialog"]').length,
        dlg: dlgRect ? {
          top: Math.round(dlgRect.top), bottom: Math.round(dlgRect.bottom),
          left: Math.round(dlgRect.left), right: Math.round(dlgRect.right),
          w: Math.round(dlgRect.width), h: Math.round(dlgRect.height),
        } : null,
        fontSizes,
        fontFamilies,
        tooSmall: tooSmall.slice(0, 8),
        tooSmallCount: tooSmall.length,
        outermost: roots.slice(0, 8),
        widest: over.slice().sort((a, b) => b.right - a.right).slice(0, 6),
        boxes: [
          main ? { sel: 'main', w: Math.round(main.getBoundingClientRect().width) } : null,
          page ? { sel: 'page', w: Math.round(page.getBoundingClientRect().width) } : null,
        ].filter(Boolean),
      });
    } catch (e) {
      out.textContent = 'PROBE:' + JSON.stringify({ error: String(e) });
    }
    };
    doClick();
    // Give the sheet's open animation a moment to settle before measuring.
    setTimeout(measure, act ? 800 : 0);
  }, 3000);
};
</script></body></html>`

writeFileSync(probeFile, probeHtml)

console.log(`mobile audit @ ${width}x${height} -> ${outDir}\n`)

const failures = []

for (const [name, route, act] of PAGES) {
  const profile = freshProfile()
  const file = join(outDir, `${name}-${width}.png`)
  const actParam = act ? `&act=${encodeURIComponent(act)}` : ''

  // 1. seed the profile with realistic data (the seed page also proves the
  //    route boots) — the seed page redirects into the app.
  try {
    chrome([
      '--headless=new', '--disable-gpu', '--no-sandbox',
      `--user-data-dir=${profile}`,
      `--window-size=${width},${height}`,
      '--virtual-time-budget=8000',
      '--dump-dom',
      `${base}/__seed.html?r=${encodeURIComponent(route)}`,
    ])
  } catch { /* seeding is best effort */ }

  // 2. measure
  let report = null
  try {
    const dom = chrome([
      '--headless=new', '--disable-gpu', '--no-sandbox',
      `--user-data-dir=${profile}`,
      `--window-size=${width},${height}`,
      '--virtual-time-budget=12000',
      '--dump-dom',
      `${base}/${probeName}?r=${encodeURIComponent(route)}${actParam}`,
    ])
    const m = dom.match(/PROBE:(\{[\s\S]*?\})<\/pre>/)
    if (m) report = JSON.parse(m[1])
  } catch (e) {
    report = { error: e.message }
  }

  // 3. photograph the measured iframe
  try {
    chrome([
      '--headless=new', '--disable-gpu', '--no-sandbox', '--hide-scrollbars',
      `--user-data-dir=${profile}`,
      `--window-size=${width},${height}`,
      '--virtual-time-budget=12000',
      `--screenshot=${file}`,
      `${base}/${probeName}?r=${encodeURIComponent(route)}${actParam}`,
    ])
  } catch (e) {
    console.log(`  ${name}: screenshot failed: ${e.message}`)
  }

  const size = existsSync(file) ? readFileSync(file).length : 0
  if (!report) {
    console.log(`  ${name.padEnd(10)} no probe result`)
    failures.push(name)
    continue
  }
  if (report.error) {
    console.log(`  ${name.padEnd(10)} probe error: ${report.error}`)
    failures.push(name)
    continue
  }

  const over = report.count > 0
  const tiny = report.tooSmallCount > 0
  console.log(
    `  ${name.padEnd(10)} ${over ? '❌' : '✅'} overflow=${report.count}  ` +
      `doc=${report.docScrollW}/${report.viewport}  ` +
      `boxes: ${report.boxes.map(b => `${b.sel}=${b.w}`).join(' ')}` +
      (tiny ? `  ⚠️ sub-7px text=${report.tooSmallCount}` : '') +
      (act ? `  dialogs=${report.dialogs} clicked=${report.clicked} dlg=${JSON.stringify(report.dlg)}` : ''),
  )
  report.tooSmall?.forEach(t =>
    console.log(`      tiny ${t.fs}px "${t.txt}" (${t.tag})`),
  )
  if (report.fontSizes) {
    const hist = Object.entries(report.fontSizes)
      .sort((a, b) => Number(a[0]) - Number(b[0]))
      .map(([px, n]) => `${px}px:${n}`)
      .join(' ')
    console.log(`      fonts: ${hist}`)
  }
  if (report.fontFamilies) {
    console.log(`      families: ${JSON.stringify(report.fontFamilies)}`)
  }
  if (over) failures.push(name)
  if (tiny) failures.push(`${name}(tiny-text)`)
  console.log(`      -> ${file} (${size} bytes)`)
}

console.log(
  failures.length
    ? `\n${failures.length} page(s) with overflow: ${failures.join(', ')}`
    : '\nNo horizontal overflow on any page.',
)

// The probe and seed pages are temporary artefacts — never leave them in
// public/ where they would be published to Firebase Hosting.
for (const f of [probeFile, seedFile]) {
  try {
    rmSync(f, { force: true })
  } catch { /* best effort */ }
}
